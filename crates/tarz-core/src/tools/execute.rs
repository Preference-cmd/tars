/// Prepared write operation details generated by precheck and executed by tools.
#[derive(Clone, Debug)]
pub(crate) struct PreparedWrite {
    pub(crate) path: String,
    pub(crate) normalized_path: String,
    pub(crate) expected_version: Option<FileVersion>,
    pub(crate) existing_mode: Option<u32>,
    pub(crate) final_content: String,
    pub(crate) diff: String,
    pub(crate) diff_summary: DiffSummary,
    pub(crate) action: WriteAction,
    pub(crate) parent_components: Vec<String>,
    pub(crate) file_name: String,
    pub(crate) bytes_written: usize,
}

/// Fixed workspace resources reused by independently bound work wrappers.
pub struct WorkspaceTools {
    workspace: Arc<Workspace>,
    limits: WorkspaceToolLimits,
    pub(super) write_limits: WriteToolLimits,
    command_settings: CommandSettings,
    pub(super) command: Option<Arc<super::CommandRuntime>>,
    pub(super) local: Arc<Semaphore>,
    host: Arc<ToolResources>,
    counters: Arc<Counters>,
    pub(super) observations: std::sync::Mutex<std::collections::HashMap<String, FileVersion>>,
    #[cfg(test)]
    pub(super) gate: std::sync::Mutex<Option<Arc<TestGate>>>,
    #[cfg(test)]
    pub(super) write_gate: std::sync::Mutex<Option<Arc<TestGate>>>,
}

impl WorkspaceTools {
    pub(crate) fn limits(&self) -> &WorkspaceToolLimits {
        &self.limits
    }
    pub(crate) fn write_limits(&self) -> &WriteToolLimits {
        &self.write_limits
    }
    pub(crate) fn command_settings(&self) -> CommandSettings {
        self.command_settings
    }
    pub(crate) fn command(&self) -> Option<&Arc<super::CommandRuntime>> {
        self.command.as_ref()
    }
    pub(crate) fn workspace(&self) -> &Workspace {
        &self.workspace
    }
    pub(crate) fn host(&self) -> &ToolResources {
        &self.host
    }
    pub(crate) fn counters(&self) -> Arc<Counters> {
        self.counters.clone()
    }
    pub(crate) fn local(&self) -> Arc<Semaphore> {
        self.local.clone()
    }
    pub(crate) fn observations(
        &self,
    ) -> &std::sync::Mutex<std::collections::HashMap<String, FileVersion>> {
        &self.observations
    }

    /// Bind a selected root to frozen application limits, default write
    /// limits and shared host slots.
    #[cfg(all(test, any(target_os = "linux", target_os = "macos")))]
    pub fn new(
        workspace: Arc<Workspace>,
        limits: WorkspaceToolLimits,
        host: Arc<ToolResources>,
    ) -> Arc<Self> {
        Self::with_write_limits(workspace, limits, WriteToolLimits::default(), host)
    }

    /// Bind a selected root to application limits, write limits, and shared host slots.
    pub fn with_write_limits(
        workspace: Arc<Workspace>,
        limits: WorkspaceToolLimits,
        write_limits: WriteToolLimits,
        host: Arc<ToolResources>,
    ) -> Arc<Self> {
        Self::with_parts(
            workspace,
            limits,
            write_limits,
            host,
            CommandSettings::default(),
            None,
        )
    }

    pub(crate) fn with_command(
        workspace: Arc<Workspace>,
        limits: WorkspaceToolLimits,
        write_limits: WriteToolLimits,
        host: Arc<ToolResources>,
        command_settings: CommandSettings,
        command: Option<Arc<super::CommandRuntime>>,
    ) -> Arc<Self> {
        Self::with_parts(
            workspace,
            limits,
            write_limits,
            host,
            command_settings,
            command,
        )
    }

    fn with_parts(
        workspace: Arc<Workspace>,
        limits: WorkspaceToolLimits,
        write_limits: WriteToolLimits,
        host: Arc<ToolResources>,
        command_settings: CommandSettings,
        command: Option<Arc<super::CommandRuntime>>,
    ) -> Arc<Self> {
        Arc::new(Self {
            workspace,
            local: Arc::new(Semaphore::new(limits.max_concurrent_operations)),
            limits,
            write_limits,
            command_settings,
            command,
            host,
            counters: Arc::new(Counters::default()),
            observations: std::sync::Mutex::new(std::collections::HashMap::new()),
            #[cfg(test)]
            gate: std::sync::Mutex::new(None),
            #[cfg(test)]
            write_gate: std::sync::Mutex::new(None),
        })
    }

    /// Produce new per-work tool wrappers for test runs with an empty prepared map.
    #[cfg(test)]
    pub(crate) fn bind_for_test(
        self: &Arc<Self>,
        selected: &[WorkspaceTool],
        reporter: ToolReporter,
    ) -> Vec<Arc<dyn Tool>> {
        self.bind_with_prepared(
            selected,
            reporter,
            Arc::new(std::sync::Mutex::new(std::collections::HashMap::new())),
        )
    }

    /// Produce new per-work tool wrappers sharing turn-scoped prepared writes.
    pub(crate) fn bind_with_prepared(
        self: &Arc<Self>,
        selected: &[WorkspaceTool],
        reporter: ToolReporter,
        prepared: Arc<
            std::sync::Mutex<std::collections::HashMap<causa::kernel::BlockId, PreparedWrite>>,
        >,
    ) -> Vec<Arc<dyn Tool>> {
        selected
            .iter()
            .map(|kind| {
                Arc::new(WorkspaceToolImpl {
                    shared: self.clone(),
                    kind: *kind,
                    reporter: reporter.clone(),
                    prepared: prepared.clone(),
                }) as Arc<dyn Tool>
            })
            .collect()
    }

    /// Observe actual filesystem resource counters without reading tool materials.
    #[cfg(test)]
    pub fn metrics(&self) -> ToolMetrics {
        self.counters.snapshot()
    }

    #[cfg(test)]
    pub(crate) fn set_write_gate(&self, gate: Option<Arc<TestGate>>) {
        *self.write_gate.lock().expect("write gate lock") = gate;
    }
}

struct WorkspaceToolImpl {
    shared: Arc<WorkspaceTools>,
    kind: WorkspaceTool,
    reporter: ToolReporter,
    prepared:
        Arc<std::sync::Mutex<std::collections::HashMap<causa::kernel::BlockId, PreparedWrite>>>,
}

struct CancelOnDrop(CancellationToken);
impl Drop for CancelOnDrop {
    fn drop(&mut self) {
        self.0.cancel();
    }
}

pub(crate) fn result(
    call: &ToolCallContext,
    status: ToolResultStatus,
    content: serde_json::Value,
) -> ToolResultPayload {
    ToolResultPayload::new(call.call_block_id, status, ToolOutput::new(content))
}

fn stopped(call: &ToolCallContext, control: &CallControl) -> ToolResultPayload {
    let status = if control.is_cancelled() {
        ToolResultStatus::Cancelled
    } else {
        ToolResultStatus::TimedOut
    };
    result(
        call,
        status,
        serde_json::json!({"error":"operation stopped before obtaining a result"}),
    )
}

/// A command that expired or was stopped while queued never started a process.
/// It is rejected rather than reported as timed out or cancelled, so the model
/// cannot read it as a command that ran and hung, and repair warning rules,
/// which treat timed-out and cancelled commands as possibly executed, ignore it.
fn not_started(call: &ToolCallContext, control: &CallControl) -> ToolResultPayload {
    let cause = if control.is_cancelled() {
        "the work was stopped while this command was waiting for the previous command"
    } else {
        "the deadline expired while this command was waiting for the previous command"
    };
    result(
        call,
        ToolResultStatus::Rejected,
        serde_json::json!({
            "error": "the command was not started",
            "reason": format!(
                "commands in one session run one at a time; {cause}, so no process was started"
            ),
        }),
    )
}

impl WorkspaceToolImpl {
    async fn execute_command(
        &self,
        call: &ToolCallContext,
        control: &CallControl,
        params: Params,
    ) -> ToolResultPayload {
        let Params::Command(params) = params else {
            return result(
                call,
                ToolResultStatus::Rejected,
                serde_json::json!({ "error": "invalid command parameters" }),
            );
        };
        let Some(runtime) = self.shared.command.as_ref() else {
            let output = result(
                call,
                ToolResultStatus::Rejected,
                serde_json::json!({ "error": "command runtime is not available" }),
            );
            self.reporter.returned(call, output.status.clone());
            return output;
        };
        let prepared = match runtime.check(&params) {
            Ok(prepared) => prepared,
            Err(error) => {
                let output = result(
                    call,
                    ToolResultStatus::Rejected,
                    serde_json::json!({ "error": error }),
                );
                self.reporter.returned(call, output.status.clone());
                return output;
            }
        };
        let command_control = control.with_timeout(super::command::bounded_timeout(
            control.deadline(),
            Duration::from_secs(prepared.timeout_secs),
        ));
        self.reporter.waiting(call);
        let Some(permit) = runtime.acquire(&command_control).await else {
            let output = not_started(call, &command_control);
            self.reporter.returned(call, output.status.clone());
            return output;
        };
        self.reporter.running(call);
        let execution = runtime
            .run(
                prepared,
                permit,
                &command_control,
                self.shared.limits.max_output_bytes,
            )
            .await;
        let mut output = result(call, execution.status, execution.content);
        if serde_json::to_vec(&output).map_or(true, |bytes| {
            bytes.len() > self.shared.limits.max_output_bytes
        }) {
            output.output.content = serde_json::json!({
                "truncated": true,
                "complete": false,
                "limit_reason": "output_bytes"
            });
        }
        self.reporter.returned(call, output.status.clone());
        output
    }
}

#[async_trait::async_trait]
impl Tool for WorkspaceToolImpl {
    fn definition(&self) -> ToolDefinition {
        use serde_json::json;
        let (name, description, fields) = match self.kind {
            WorkspaceTool::ListDirectory => (
                "list_directory",
                "List a single workspace-relative directory without following links.",
                json!({"path":{"type":"string","maxLength":4096},"limit":{"type":"integer","minimum":1,"maximum":self.shared.limits.max_directory_entries}}),
            ),
            WorkspaceTool::ReadFile => (
                "read_file",
                "Read UTF-8 lines from a regular workspace-relative file; line numbers start at one.",
                json!({"path":{"type":"string","maxLength":4096},"start_line":{"type":"integer","minimum":1},"max_lines":{"type":"integer","minimum":1,"maximum":2000}}),
            ),
            WorkspaceTool::SearchText => (
                "search_text",
                "Search single-line literal text (at most 1024 UTF-8 bytes) in bounded workspace files; partial scans are explicitly marked.",
                json!({"path":{"type":"string","maxLength":4096},"query":{"type":"string","minLength":1,"maxLength":1024},"max_matches":{"type":"integer","minimum":1,"maximum":self.shared.limits.max_search_matches}}),
            ),
            WorkspaceTool::WriteFile => (
                "write_file",
                "Write full UTF-8 content to a workspace-relative file, creating missing directories or overwriting atomically.",
                json!({"path":{"type":"string","maxLength":4096},"content":{"type":"string"}}),
            ),
            WorkspaceTool::EditFile => (
                "edit_file",
                "Replace exact text segments in a workspace-relative file; all edits apply simultaneously against the original content.",
                json!({
                    "path": {"type":"string","maxLength":4096},
                    "edits": {
                        "type": "array",
                        "minItems": 1,
                        "maxItems": self.shared.write_limits.max_edit_segments,
                        "items": {
                            "type": "object",
                            "properties": {
                                "old_text": {"type": "string"},
                                "new_text": {"type": "string"}
                            },
                            "required": ["old_text", "new_text"],
                            "additionalProperties": false
                        }
                    }
                }),
            ),
            WorkspaceTool::RunCommand => (
                "run_command",
                "Run one shell command in a sandboxed workspace; network is disabled unless the session enables it.",
                json!({
                    "command": {"type":"string","minLength":1,"maxLength":16384},
                    "workdir": {"type":"string","maxLength":4096},
                    "timeout_secs": {"type":"integer","minimum":1,"maximum":self.shared.command_settings().max_timeout_secs}
                }),
            ),
        };
        let required = match self.kind {
            WorkspaceTool::SearchText => json!(["path", "query"]),
            WorkspaceTool::WriteFile => json!(["path", "content"]),
            WorkspaceTool::EditFile => json!(["path", "edits"]),
            WorkspaceTool::RunCommand => json!(["command"]),
            _ => json!(["path"]),
        };
        ToolDefinition::new(
            name,
            description,
            json!({"type":"object","properties":fields,"required":required,"additionalProperties":false}),
        )
    }

    fn hints(&self) -> causa::kernel::ToolHints {
        match self.kind {
            WorkspaceTool::ListDirectory | WorkspaceTool::ReadFile | WorkspaceTool::SearchText => {
                causa::kernel::ToolHints::default()
                    .with_read_only(true)
                    .with_open_world(false)
            }
            WorkspaceTool::WriteFile => causa::kernel::ToolHints::default()
                .with_read_only(false)
                .with_destructive(true)
                .with_idempotent(true)
                .with_open_world(false),
            WorkspaceTool::EditFile => causa::kernel::ToolHints::default()
                .with_read_only(false)
                .with_destructive(true)
                .with_idempotent(false)
                .with_open_world(false),
            WorkspaceTool::RunCommand => causa::kernel::ToolHints::default()
                .with_read_only(false)
                .with_destructive(true)
                .with_idempotent(false)
                .with_open_world(false),
        }
    }
    async fn execute(
        &self,
        call: &ToolCallContext,
        control: &CallControl,
        _store: Option<&dyn causa::kernel::ArtifactStore>,
    ) -> ToolResultPayload {
        let params = if call.input.tool_name == self.definition().name {
            Params::decode(
                self.kind,
                &call.input.arguments,
                &self.shared.limits,
                &self.shared.write_limits,
                self.shared.command_settings(),
            )
        } else {
            Err(std::borrow::Cow::Borrowed(
                "tool name does not match bound capability",
            ))
        };
        let params = match params {
            Ok(params) => params,
            Err(error) => {
                let output = result(
                    call,
                    ToolResultStatus::Rejected,
                    serde_json::json!({"error": error.to_string()}),
                );
                self.reporter.returned(call, output.status.clone());
                return output;
            }
        };
        if self.kind == WorkspaceTool::RunCommand {
            return self.execute_command(call, control, params).await;
        }
        let prepared_write = match self.kind {
            WorkspaceTool::WriteFile | WorkspaceTool::EditFile => {
                let prepared = self.prepared.lock().unwrap().remove(&call.call_block_id);
                match prepared {
                    Some(p) => Some(p),
                    None => {
                        let output = result(
                            call,
                            ToolResultStatus::Rejected,
                            serde_json::json!({"error": "write operation was not prepared by precheck"}),
                        );
                        self.reporter.returned(call, output.status.clone());
                        return output;
                    }
                }
            }
            _ => None,
        };

        let control =
            control.with_timeout(Duration::from_secs(self.shared.limits.call_timeout_secs));
        self.reporter.waiting(call);
        #[cfg(test)]
        self.shared
            .host
            .counters
            .test_wrappers_entered
            .fetch_add(1, std::sync::atomic::Ordering::SeqCst);
        let acquire = async {
            let local = self.shared.local.clone().acquire_owned().await.ok()?;
            let host = self.shared.host.slots.clone().acquire_owned().await.ok()?;
            Some((host, local))
        };
        let deadline = async {
            if let Some(deadline) = control.deadline() {
                tokio::time::sleep_until(deadline.into()).await;
            } else {
                std::future::pending::<()>().await;
            }
        };
        let permits = tokio::select! {
            biased;
            _ = control.cancellation_token().cancelled() => None,
            _ = deadline => None,
            permits = acquire => permits,
        };
        let Some((host, local)) = permits else {
            return stopped(call, &control);
        };
        if control.check().is_err() {
            return stopped(call, &control);
        }
        let dropstop = CancellationToken::new();
        let _cancel = CancelOnDrop(dropstop.clone());
        let worker_control = OperationControl {
            call: control.clone(),
            dropstop,
            counters: self.shared.counters.clone(),
            host_counters: self.shared.host.counters.clone(),
        };
        let shared = self.shared.clone();
        let call_owned = call.clone();
        let reporter = self.reporter.clone();
        let worker = self.reporter.spawn_blocking(move || {
            if worker_control.check().is_err() { return stopped(&call_owned, &worker_control.call); }
            let guard = OperationGuard { counters: shared.counters.clone(), host_counters: shared.host.counters.clone(), _local: local, _host: host };
            guard.start();
            reporter.running(&call_owned);
            #[cfg(test)]
            if let Some(gate) = shared.gate.lock().expect("gate lock").clone() {
                gate.pause(false);
            }
            let output = if let Some(prepared) = &prepared_write {
                super::operations::execute_prepared_write(
                    &shared.workspace,
                    prepared,
                    &shared.write_limits,
                    &shared.observations,
                    &worker_control,
                    #[cfg(test)]
                    &shared.write_gate,
                )
            } else {
                run(
                    &shared.workspace,
                    &params,
                    &shared.limits,
                    &shared.write_limits,
                    &shared.observations,
                    &worker_control,
                    #[cfg(test)]
                    &shared.write_gate,
                )
            };
            let mut output = match output {
                Ok(content) => result(&call_owned, ToolResultStatus::Succeeded, content),
                Err(error) => result(&call_owned, error.status(), serde_json::json!({"error":error.to_string()})),
            };
            // Bound the entire serialized result, including identity and JSON escaping.
            if serde_json::to_vec(&output).map_or(true, |bytes| bytes.len() > shared.limits.max_output_bytes) {
                output.output.content = serde_json::json!({"truncated":true,"complete":false,"limit_reason":"output_bytes"});
            }
            #[cfg(test)]
            if let Some(gate) = shared.gate.lock().expect("gate lock").clone() {
                gate.pause(true);
            }
            reporter.returned(&call_owned, output.status.clone());
            output
        });
        match worker.await {
            Ok(output) => output,
            Err(_) => result(
                call,
                ToolResultStatus::Failed,
                serde_json::json!({"error":"filesystem worker failed"}),
            ),
        }
    }
}

#[cfg(test)]
pub(crate) struct TestGate {
    pub(crate) before_return: bool,
    pub(crate) reached: tokio::sync::Notify,
    pub(crate) released: std::sync::Mutex<bool>,
    pub(crate) changed: std::sync::Condvar,
}
#[cfg(test)]
impl TestGate {
    #[allow(dead_code)]
    pub(crate) fn new(before_return: bool) -> Arc<Self> {
        Arc::new(Self {
            before_return,
            reached: tokio::sync::Notify::new(),
            released: std::sync::Mutex::new(false),
            changed: std::sync::Condvar::new(),
        })
    }
    pub(super) fn pause(&self, before_return: bool) {
        if self.before_return != before_return {
            return;
        }
        self.reached.notify_one();
        let mut released = self.released.lock().expect("gate release lock");
        while !*released {
            released = self.changed.wait(released).expect("gate wait");
        }
    }
    pub(crate) fn release(&self) {
        *self.released.lock().expect("gate release lock") = true;
        self.changed.notify_all();
    }
}
